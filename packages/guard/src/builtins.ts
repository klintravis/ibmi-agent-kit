// Built-in function policy: a function call is `call` unless it is a Db2 for i built-in listed in
// BUILTINS (unqualified, or qualified to SYSIBM, SYSFUN or QSYS2). QSYS2 and SYSTOOLS *services*
// (QSYS2.IFS_READ, SYSTOOLS.HTTPGETCLOB, QSYS2.DELIMIT_NAME, ...) are ordinary user-visible
// functions, so they are `call` on their schema, with one exception: a table function listed in
// CATALOG_TABLE_FUNCTIONS, used as `TABLE(QSYS2.OBJECT_STATISTICS(...))` in a FROM clause, only
// reads catalog or job information and is a `read` of that function. The list is deliberately
// short; a policy decides `call` on QSYS2 like any other library.

